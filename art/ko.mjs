// Writes game/assets/ko.svg: the KO burst where a knocked-out character leaves the screen (Character.blast).
// A strip of FRAMES frames, each FRAME_W×FRAME_H at the size the game shows it (no scaling), base centered on the
// bottom edge and spikes pointing up: solid white with sharp edges, to match the sudden death action lines.
// Seeded, so rerunning gives the same file; change SEED (or the numbers below) and rerun:
//   node art/ko.mjs
import { writeFileSync } from 'node:fs';

const SEED = 7;
const FRAMES = 6;
const FRAME_W = 256;
const FRAME_H = 512;
const HEIGHTS = [0.78, 1, 0.9, 1.04, 0.84, 0.96];   // per frame, of the tallest spike; the burst flickers through them
const REACH = { x: 110, y: 420 };   // the ellipse spike tips stay inside, from the fan center
const CENTER_DROP = 20;             // the fan's center sits this far below the frame's bottom edge
const BASE_HALF = 90;               // half the width where the burst meets the bottom edge

let seed = SEED;
const random = () => ((seed = (seed * 16807) % 2147483647) - 1) / 2147483646;
const between = (min, max) => min + random() * (max - min);
const round = (n) => Math.round(n * 10) / 10;

function frame(height) {
  const cx = FRAME_W / 2, cy = FRAME_H + CENTER_DROP;
  const at = (angle, r) => [round(cx + Math.cos(angle) * r), round(cy + Math.sin(angle) * r)];
  // How far a tip can reach at this angle: the ellipse, so the middle spikes are the tall ones.
  const reach = (angle) => 1 / Math.hypot(Math.cos(angle) / REACH.x, Math.sin(angle) / (REACH.y * height));

  // One tall spike straight up (give or take), then one or two shorter ones on each side, leaning further out.
  // SVG angles: -90° is straight up.
  const up = -Math.PI / 2 + between(-0.06, 0.06);
  const tips = [{ angle: up, r: reach(up) }];
  for (const side of [-1, 1]) {
    let angle = up, r = tips[0].r;
    for (let i = 0, n = Math.round(between(1, 2)); i < n; i++) {
      angle += side * between(0.3, 0.42);
      r = Math.min(r * between(0.5, 0.8), reach(angle) * 0.9);
      tips[side < 0 ? 'unshift' : 'push']({ angle, r });
    }
  }

  // Outline: in from the bottom left, then each spike's tip with a valley between it and the next, out at the bottom
  // right. Each side of a spike bends in toward the spike's middle, so the sides are concave and the tips needle sharp.
  const start = [round(cx - BASE_HALF), FRAME_H];
  const end = [round(cx + BASE_HALF), FRAME_H];
  const valleys = tips.slice(1).map((tip, i) => {
    const prev = tips[i];
    return { angle: (prev.angle + tip.angle) / 2 + between(-0.03, 0.03), r: Math.min(prev.r, tip.r) * between(0.55, 0.7) };
  });
  const toward = (valley, tip) => at(valley.angle + (tip.angle - valley.angle) * 0.5, valley.r + (tip.r - valley.r) * 0.35);
  let d = `M${start} L${at(tips[0].angle - 0.2, tips[0].r * 0.3)} L${at(tips[0].angle, tips[0].r)}`;
  valleys.forEach((valley, i) => {
    d += ` Q${toward(valley, tips[i])} ${at(valley.angle, valley.r)}`;
    d += ` Q${toward(valley, tips[i + 1])} ${at(tips[i + 1].angle, tips[i + 1].r)}`;
  });
  const last = tips[tips.length - 1];
  d += ` L${at(last.angle + 0.2, last.r * 0.3)} L${end} Z`;

  // A couple of loose shards flying off past the spike tips.
  const shards = [];
  for (let i = 0, n = Math.round(between(1, 3)); i < n; i++) {
    const tip = tips.splice(Math.floor(random() * tips.length), 1)[0];   // a different tip each
    const angle = tip.angle + between(-0.12, 0.12);
    const r = Math.min(tip.r + between(32, 70), reach(angle) * 1.05);
    const length = between(18, 34), width = between(5, 8);
    const [x, y] = at(angle, r);
    const [ux, uy] = [Math.cos(angle), Math.sin(angle)];
    shards.push(`M${round(x - ux * length / 2)},${round(y - uy * length / 2)} L${round(x - uy * width)},${round(y + ux * width)}`
      + ` L${round(x + ux * length / 2)},${round(y + uy * length / 2)} L${round(x + uy * width)},${round(y - ux * width)} Z`);
  }
  return { d, shards };
}

const groups = HEIGHTS.slice(0, FRAMES).map((height, i) => {
  const { d, shards } = frame(height);
  return `  <g transform="translate(${i * FRAME_W} 0)" clip-path="url(#frame)">\n`
    + `    <path d="${d}"/>\n`
    + shards.map((s) => `    <path d="${s}"/>\n`).join('')
    + '  </g>';
});

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${FRAMES * FRAME_W}" height="${FRAME_H}" viewBox="0 0 ${FRAMES * FRAME_W} ${FRAME_H}">
  <!-- Generated by art/ko.mjs; edit that and rerun instead of editing this. -->
  <defs><clipPath id="frame"><rect width="${FRAME_W}" height="${FRAME_H}"/></clipPath></defs>
  <style>path { fill: #fff }</style>
${groups.join('\n')}
</svg>
`;
writeFileSync(new URL('../game/assets/ko.svg', import.meta.url), svg);
